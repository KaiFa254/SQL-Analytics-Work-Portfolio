WITH SnapshotDates AS (
    SELECT DISTINCT EXTRACTION_DATE AS SNAPSHOT_DATE
    FROM dbcba.KE_Accounts_Master
    WHERE EXTRACTION_DATE IN (
       '2025-03-31', '2025-06-30', '2025-09-30', '2025-11-30'
    )
),
ProductCounts AS (
    SELECT
        CUSTOMER,
        EXTRACTION_DATE,
        SUM(CASE WHEN CATEGORY IN ('1001','1017','1033','1454','1132','1078','1452','1138','1153','21002') 
                 AND ONLINE_ACTUAL_BAL > 0 THEN 1 ELSE 0 END) AS CURRENTAC,
        SUM(CASE WHEN CATEGORY IN ('6001','6002','6003','6010','6011','6015','6016','6020','6021','6025','6050','6055','6056','6058','6200','6202') 
                 THEN 1 ELSE 0 END) AS SAVINGSAC,
        SUM(CASE WHEN CATEGORY IN ('3201','3202','3203','3204','3206','3207','6501','6502','6503','6505','6507','6511','6515','6520','6525','6526','6527','6528','6529','6530','6531','6550','6555','6560','6565','6600','6601','6602','6603','6604') 
                 AND ONLINE_ACTUAL_BAL <> 0 THEN 1 ELSE 0 END) AS TERMAC,
        SUM(CASE WHEN CATEGORY IN ('1001','1017','1033','1454','1132','1078','1452','1138','1153','21002') 
                 AND ONLINE_ACTUAL_BAL < 0 THEN 1 ELSE 0 END) AS ODAC,
        SUM(CASE WHEN CATEGORY IN ('3100','3101','3104','3109','3200','3220','3280','3319','3321','3335','3370','3500','3510','3560','3575','3610','3615','3715','3716','3717','3718','3719','3720','3721','3722','3723','3724','3725','3726','3727','3728','3729','3730','3731','3732') 
                 AND ONLINE_ACTUAL_BAL < 0 THEN 1 ELSE 0 END) AS AFLOAN,
        SUM(CASE WHEN CATEGORY IN ('3113','3114','3119','3286','3765') 
                 AND ONLINE_ACTUAL_BAL < 0 THEN 1 ELSE 0 END) AS MLLOAN,
        SUM(CASE WHEN CATEGORY IN ('3110','3205','3210','3215','3225','3235','3240','3300','3350','3360','3365','3375','3386','3395','3505','3515','3607','3608','3620','3625','3630','3700','3701','3702','3704','3705','3706','3710','3711','3714','3740','3748','3749','3750','3751') 
                 AND ONLINE_ACTUAL_BAL < 0 THEN 1 ELSE 0 END) AS HLLOAN,
        SUM(CASE WHEN CATEGORY IN ('3102','3103','3105','3106','3107','3108','3111','3112','3115','3118','3230','3245','3250','3255','3260','3265','3270','3275','3285','3287','3290','3295','3310','3315','3320','3340','3355','3380','3385','3387','3400','3550','3555','3565','3570','3600','3601','3602','3603','3604','3605','3606','3703','3707','3708','3709','3712','3713','3734','3735','3736','3737','3738','3739','3741','3742','3743','3744','3745','3746','3747','3752','3753','3754','3755','3756','3758','3759','3760','3761','3762','3763') 
                 THEN 1 ELSE 0 END) AS PULLOAN
       FROM dbcba.KE_Accounts_Master a
    INNER JOIN SnapshotDates s
        ON a.EXTRACTION_DATE = s.SNAPSHOT_DATE
    GROUP BY a.CUSTOMER, a.EXTRACTION_DATE
)

SELECT
    sd.SNAPSHOT_DATE,
    cm.CUSTOMER_NUMBER AS CUSTOMER_ID,
    COALESCE(pc.CURRENTAC,0) AS CURRENT_ACCOUNTS,
    COALESCE(pc.SAVINGSAC,0) AS SAVINGS_ACCOUNTS,
    COALESCE(pc.TERMAC,0) AS TERM_DEPOSITS,
    COALESCE(pc.ODAC,0) AS OD_ACCOUNTS,
    COALESCE(pc.AFLOAN,0) AS ASSET_FINANCE_LOANS,
    COALESCE(pc.MLLOAN,0) AS MOBILE_LOANS,
    COALESCE(pc.HLLOAN,0) AS MORTGAGE_LOANS,
    COALESCE(pc.PULLOAN,0) AS PUL_LOANS,
    
    -- PPC
    (
        CASE WHEN COALESCE(pc.CURRENTAC,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.SAVINGSAC,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.TERMAC,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.ODAC,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.AFLOAN,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.MLLOAN,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.HLLOAN,0)>0 THEN 1 ELSE 0 END +
        CASE WHEN COALESCE(pc.PULLOAN,0)>0 THEN 1 ELSE 0 END
    ) AS PPC
FROM SnapshotDates sd
INNER JOIN dbcba.KE_Customer_Master cm
    ON cm.EXTRACTION_DATE = sd.SNAPSHOT_DATE
LEFT JOIN ProductCounts pc
    ON pc.CUSTOMER = cm.CUSTOMER_NUMBER
    AND pc.EXTRACTION_DATE = cm.EXTRACTION_DATE
ORDER BY sd.SNAPSHOT_DATE;