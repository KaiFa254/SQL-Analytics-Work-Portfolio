SELECT DISTINCT
    acc.CUSTOMER,cm.SUB_SEGEMENT_DESC,cm.BUSINESS_SEGMENT_DESC ,
    CASE 
        WHEN mob_Act_chk.Customer_number IS NULL THEN 'not_reg' 
        ELSE mob_Act_chk.mob_Act_chk 
    END AS mobile_Bank_days_since_last_use,
    COALESCE(DEB.DEBIT, 0) AS Debit_Cards,
    COALESCE(CRED.CREDIT, 0) AS CrediCards,
    COALESCE (CA.CURRENTAC,0) AS CurrentAcc,
    COALESCE (SA.SAVINGSAC,0) AS SavingsAcc,
    COALESCE (TD.TERMAC,0) AS TermDeposits,
    COALESCE (OD.ODAC,0) AS OD,
    COALESCE (AF.AFLOAN,0) AS AssetFinance,
    COALESCE (ML.MLLOAN,0) AS MobileLoans,
    COALESCE (HL.HLLOAN,0) AS MORTGAGE,
    COALESCE (PUL.PULLOAN,0) AS PersonalLoans,
    (CASE WHEN COALESCE(CRED.CREDIT, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(CA.CURRENTAC, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(SA.SAVINGSAC, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(TD.TERMAC, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(OD.ODAC, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(AF.AFLOAN, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(ML.MLLOAN, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(HL.HLLOAN, 0) > 0 THEN 1 ELSE 0 END +
     CASE WHEN COALESCE(PUL.PULLOAN, 0) > 0 THEN 1 ELSE 0 END
     ) 
     AS PPC
    
FROM dbcba.KE_Accounts_List acc
INNER JOIN dbcba.ke_Customer_master cm ON acc.customer = cm.Customer_number AND cm.EXTRACTION_DATE =(select max(EXTRACTION_DATE) from  dbcba.KE_Customer_Master)
LEFT JOIN (
    SELECT DISTINCT CUSTOMER, MIN(opening_date) AS CREATION_DATE
    FROM dbcba.KE_Accounts_List
    WHERE co_code = 'KE0010001' AND CUSTOMER IS NOT NULL AND CUSTOMER <> ''
    GROUP BY CUSTOMER
) cr ON cr.customer = cm.Customer_number
LEFT JOIN (
    SELECT DISTINCT 
        mc.Customer_number, 
        CASE 
            WHEN DATEDIFF(DAY, MAX(TXDTE), GETDATE()) <= 30 THEN 'Zero_to_30DAYS' 
            WHEN DATEDIFF(DAY, MAX(TXDTE), GETDATE()) <= 60 THEN '31Days_to_60DAYS' 
            WHEN DATEDIFF(DAY, MAX(TXDTE), GETDATE()) <= 90 THEN '60Days_to_90DAYS' 
            ELSE 'Inactive' 
        END AS mob_Act_chk 
    FROM dbcba.NCBANOW_CUSTOMERS mc 
    LEFT JOIN (
        SELECT BankAccountID, MAX(TXDate) AS TXDTE 
        FROM dbcba.NCBANOW_TRANSACTIONS 
       WHERE TxDate > DATEADD(MONTH, -12, GETDATE()) AND Amount > 0 
        GROUP BY BankAccountID
    ) mt ON mt.BankAccountID = mc.BankAccountID
    GROUP BY mc.Customer_number
) mob_Act_chk ON mob_Act_chk.Customer_number = cm.CUSTOMER_NUMBER

LEFT JOIN (
    SELECT  DISTINCT A.CUSTOMER_NUMBER, COUNT(A.CARD_NUMBER) AS DEBIT
    FROM stgke.STG_DEBIT_CREDIT_CARD A 
    WHERE A.EXTRACT_DATE = (select max(EXTRACT_DATE) from stgke.STG_DEBIT_CREDIT_CARD)
    AND A.CARD_TYPE = 'DEBIT' AND A.CO_CODE = 'KE0010001'  AND CUSTOMER_NUMBER IS NOT NULL
    GROUP BY A.CUSTOMER_NUMBER
) DEB ON DEB.CUSTOMER_NUMBER = cm.CUSTOMER_NUMBER
LEFT JOIN (
    SELECT  DISTINCT A.CUSTOMER_NUMBER, COUNT(A.CARD_NUMBER) AS CREDIT
    FROM stgke.STG_DEBIT_CREDIT_CARD A 
    WHERE A.EXTRACT_DATE=(select max(EXTRACT_DATE) from stgke.STG_DEBIT_CREDIT_CARD)  and A.CARD_TYPE='CREDIT' AND A.CO_CODE='KE0010001'  AND CUSTOMER_NUMBER IS NOT NULL
