WITH AA_Collateral_Unions AS (
    SELECT DISTINCT ID_COMP_1 AS AA_ARRANGEMENT, COLLAT_ID AS AA__COLLAT_ID
    FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID1 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID1 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID2 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID2 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID3 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID3 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID4 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID4 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID5 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID5 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID6 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID6 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID7 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID7 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID8 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID8 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID9 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID9 IS NOT NULL
    UNION ALL
    SELECT ID_COMP_1, COLLAT_ID10 FROM STGKE.STG_AA_ARR_OFFICERS WHERE COLLAT_ID10 IS NOT NULL
),
AA_CID_Merge AS (
    SELECT 
        ad.RECID AS COLLATERAL_ID,
        al.CUSTOMER,
        dt.COLLATERAL_TYPE_DESCRIPTION,
        al.CUS_SHORT_NAME,
        c.COLLATERAL_TYPE,
        c.DESCRIPTION,
        c.DESCRIPTION_1,
        c.CURRENCY AS COLLATERAL_VALUE_CURRENCY,
        c.VALUATION_AMT,
        c.EXECUTION_VALUE,
        c.NOMINAL_VALUE AS [MARKET VALUE],
        c.MAXIMUM_VALUE AS [CHARGED AMOUNT],
        c.INSURANCE_COVER,
        ad.VEHICLE_MODEL,
        ad.REG_NUMBER,
        ad.INSURANCE_TYPE,
        ad.INSURANCE_AMT,
        CASE 
            WHEN ISDATE(TRIM(ad.INSUR_EXP_DATE)) = 1 THEN CAST(TRIM(ad.INSUR_EXP_DATE) AS DATE)
            ELSE NULL
        END AS INSUR_EXP_DATE,
        CASE 
            WHEN ISDATE(TRIM(ad.VAL_EXPIRY_DATE)) = 1 THEN CAST(TRIM(ad.VAL_EXPIRY_DATE) AS DATE)
            ELSE NULL
        END AS VAL_EXPIRY_DATE,     
        ad.MARKET_VALUE,
        ad.FORCE_VALUE
   FROM stgke.STG_Collateral c
    INNER JOIN  AA_Collateral_Unions acu ON acu.AA__COLLAT_ID = c.RECID
    INNER JOIN stgke.STG_NIC_CO_ADDL_DETS ad ON acu.AA__COLLAT_ID = ad.RECID
    LEFT JOIN dbcba.collateral_type dt ON c.COLLATERAL_TYPE = dt.COLLATERAL_TYPE
    INNER JOIN (select DISTINCT am.CUSTOMER,cm.CUS_SHORT_NAME
					FROM 
       			 	dbcba.KE_Accounts_List am
    				INNER JOIN 
        			(select * from dbcba.KE_Customer_Master where EXTRACTION_DATE = (SELECT MAX(processing_date) FROM dbcba.end_of_day) )cm 
        			ON am.CUSTOMER = cm.CUSTOMER_NUMBER 
					WHERE  
			        am.PRODUCT_LINE = 'LENDING' 
			        AND am.ARR_STATUS IN ('CURRENT', 'EXPIRED') 
			        AND cm.BUSINESS_SEGMENT IN ('270','250','200')
			        AND cm.CLASSIFICATION <> 'B20' 
			        AND am.ONLINE_ACTUAL_BAL <= 0
			        and am.ARR_STATUS<>'AUTH'
		            AND CATEGORY NOT IN (
		                '25015','25016','25020','25021','25023','25032','25033','25035','25036','25081',
		                '25135','3315','3380','3760','3762','3321','3708','3116','3709','3335','3713',
		                '3370','3385','3730','3802','3707','3350','3115','3360','3365','3375','3731',
		                '3805','3386','3765'
		            )) al ON LEFT(c.RECID, CHARINDEX('.', c.RECID + '.') - 1) = al.CUSTOMER
    WHERE  c.COLLATERAL_TYPE IN (
            '101','152','151','103','102','104','301','621','143','311','107','157','111','153',
            '308','540','802','105','109','121','155','159','302','306','310','313','520','611',
            '631','804','106','108','110','120','154','156','158','280','303','305','307','309',
            '312','314','502','504','530','630','911','922','241','931','921','201','760','204','202','705','356','701','850','803','801','503','505','740','506','703','304'
        )
),
COVENANT_STATUS AS (
    SELECT 
        CASE 
            WHEN COLLATERAL_TYPE NOT IN ('879','121','306','530','120','305','504','201','760','204','202','152','158','156','631','611','154','155','630','153','157','151','540','280','705','931','921','356','911','701','850','803','802','502','801','804','503','505','740','506','310','309','308','307','111','303','302','110','311','143','313','621','520','703','301','922','314','312','304') 
            OR CONVERT(FLOAT, COALESCE(INSURANCE_AMT, '0')) <= 0
                THEN 'NOT APPLICABLE'
            WHEN (INSUR_EXP_DATE IS NULL OR INSUR_EXP_DATE < CURRENT_TIMESTAMP) 
                THEN 'EXPIRED'
            ELSE 'CURRENT'
        END AS [INSURANCE STATUS],
        CASE 
            WHEN COLLATERAL_TYPE NOT IN (
                '101','152','151','103','102','104','107','157','153','105','109','155','159',
                '611','631','106','108','154','156','158','630','101'
            ) 
                THEN 'NOT APPLICABLE'
            WHEN (VAL_EXPIRY_DATE IS NULL OR VAL_EXPIRY_DATE < CURRENT_TIMESTAMP) 
                THEN 'EXPIRED'
            ELSE 'CURRENT'
        END AS [VALUATION STATUS],
        CASE 
            WHEN COLLATERAL_TYPE IN ('931','911','921','922','356','701','850') THEN 'Life Cover'
            ELSE 'Others'
        END AS [LIFE COVERS],
        *
    FROM AA_CID_Merge
)
SELECT DISTINCT *
FROM COVENANT_STATUS
ORDER BY CUSTOMER;



