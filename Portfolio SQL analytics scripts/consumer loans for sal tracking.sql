select  am.CUSTOMER,am.ARRANGEMENT_ID,am.ACCOUNT_NUMBER,am.CATEGORY_DESC,am.CURRENCY,am.EXCHANGE_RATE, am.INTEREST_RATE,am.TERM_AMOUNT as DISBURSED_AMT,
ex.Deal_balance as EXPOSURE_ACTUAL, 
case 
	when am.CURRENCY ='KES' then ex.Deal_balance 
	else ex.Deal_balance*am.EXCHANGE_RATE
end as EXPOSURE_KES,
am.VALUE_DATE,
am.MATURITY_DATE,CONVERT(DECIMAL(18,2),am.REPAYMENT_AMT) as EMI,e.total_CREDITS as SOW_CREDITS, am.ARR_STATUS AS LOAN_STATUS, 
cm.CUS_SHORT_NAME, am.CATEGORY,am.CATEGORY_DESC,cm.LEGAL_IDNO,cm.EMPLOYMENT_STATUS,cm.EMPLOYERS_NAME,
cm.CLASSIFICATION,cm.BUSINESS_SEGMENT, cm.BUSINESS_SEGMENT_DESC, cm.SUB_SEGEMENT, cm.SUB_SEGEMENT_DESC
FROM dbcba.KE_Accounts_Master am
INNER JOIN dbcba.KE_Customer_Master cm
on am.CUSTOMER =cm.CUSTOMER_NUMBER and am.EXTRACTION_DATE=cm.EXTRACTION_DATE
left join  (select CUSTOMER_NUMBER ,sum(TOTAL_CREDITS) as total_CREDITS  from stgke.STG_SOW_TOTAL_CREDITS
where TXN_YEAR_MONTH ='2024-9'
group by CUSTOMER_NUMBER ) e
on e.CUSTOMER_NUMBER=am.CUSTOMER 
LEFT JOIN stgke.STG_ECB_TOTAL_EXPOSURE ex
on am.ACCOUNT_NUMBER=ex.RECID
where cm.EXTRACTION_DATE =(select max(processing_date) from dbcba.end_of_day)
and PRODUCT_LINE ='LENDING' AND ARR_STATUS ='CURRENT' and cm.BUSINESS_SEGMENT in ('270','250')
